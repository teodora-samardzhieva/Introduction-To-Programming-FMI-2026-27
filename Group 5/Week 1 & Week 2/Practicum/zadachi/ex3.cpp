// Задача 3. Напишете програма, която чете 2 числа(>=10) от конзолата и извежда число, образувано от последните две цифри на първото, долепени вляво от последните две цифри на второто.

// Вход:
//  1234 5678
// Изход:
//  3478

#include <iostream>

using namespace std;

int main() {
    int num1, num2;
    cin >> num1 >> num2;

    // Взимаме последните две цифри на всяко от числата чрез операция остатък с 100
    int lastTwo1 = num1 % 100;
    int lastTwo2 = num2 % 100;

    // За да ги залепим, така че последните две на първото да са вляво от тези на второто,
    // умножаваме първото число по 100 и добавяме второто.
    // Например: 34 * 100 + 78 = 3400 + 78 = 3478
    int result = lastTwo1 * 100 + lastTwo2;

    cout << result << endl;

    return 0;
}