// Бонус Задача 18. Чичо Киро, бивш програмист, в момента безработен, имал ферма, в която отглеждал крави и кокошки, но постоянно забравял по колко има от всяко животно. Поради някаква странна причина му било много по-лесно да помни колко общо били всички животни и общо колко крака имат те. Затова един ден той решил да си напише програма, която по дадени тези два параметъра, извежда колко на брой са кравите и колко на брой са кокошките в неговата ферма.

// На първите два реда се въвеждат съответно броя на животните и броя на краката. На следващите два реда се извеждат първо броя на кравите, после броя на кокошките. В случай, че такова разпределение не е възможно да се изведе подходящо съобщение. Не забравяйте да проверите дали входните данни са валидни

#include <iostream>

using namespace std;

int main() {
    int totalAnimals, totalLegs;
    cin >> totalAnimals >> totalLegs;

    // Валидация на входните данни:
    // 1. Броят на животните не може да е отрицателен.
    // 2. Броят на краката не може да е отрицателен.
    // 3. Всяка крава има 4 крака, а всяка кокошка има 2 крака. 
    //    Затова общият брой крака трябва да е четно число, 
    //    не може да бъде по-малък от 2 * общия брой животни (ако всички са кокошки) 
    //    и не може да бъде по-голям от 4 * общия брой животни (ако всички са крави).
    if (totalAnimals < 0 || totalLegs < 0 || totalLegs % 2 != 0 || 
        totalLegs < 2 * totalAnimals || totalLegs > 4 * totalAnimals) {
        cout << "Invalid input! Such distribution is not possible." << endl;
        return 0;
    }

    // Нека C е брой крави, а K е брой кокошки:
    // C + K = totalAnimals  =>  K = totalAnimals - C
    // 4*C + 2*K = totalLegs
    // 4*C + 2*(totalAnimals - C) = totalLegs
    // 4*C + 2*totalAnimals - 2*C = totalLegs
    // 2*C = totalLegs - 2*totalAnimals
    // C = (totalLegs - 2 * totalAnimals) / 2

    int cows = (totalLegs - 2 * totalAnimals) / 2;
    int chickens = totalAnimals - cows;

    // Допълнителна проверка дали получените бройки са валидни (неотрицателни)
    if (cows < 0 || chickens < 0) {
        cout << "Invalid input! Such distribution is not possible." << endl;
    } else {
        cout << cows << endl;
        cout << chickens << endl;
    }

    return 0;
}