// Бонус Задача 19. Даден е затворен интервал от ASCII кодове [a, b], начален символ (код) x и цяло число k. Да се намери ASCII кодът, получен при циклично изместване на символа x с k позиции в рамките на интервала [a, b].

// Вход: На един ред са дадени четири цели числа (или символи, ако предпочетете въвеждане като букви):

// a b x k
// където:

// a – ASCII код (или символ) на началото на интервала;
// b – ASCII код (или символ) на края на интервала;
// x – ASCII код (или символ), който ще изместваме;
// k – цяло число, показващо броя позиции за изместване (може да е отрицателно или много голямо). 
// Изход: Едно цяло число – ASCII кодът на символа, получен след изместването.

// Детайли (какво означава “циклично”): ако минем края b, “прескачаме” в началото a, и обратно при отрицателни стъпки.

// Примери:

// Вход:
// a d c 3
// Изход:
// b

// Вход:
// a d c -3
// Изход:
// d

#include <iostream>

using namespace std;

int main() {
    char aChar, bChar, xChar;
    long long k;

    // Четеме границите на интервала, началния символ и броя позиции за изместване
    cin >> aChar >> bChar >> xChar >> k;

    // Превръщаме символите в техните целочислени ASCII кодове
    long long a = static_cast<long long>(aChar);
    long long b = static_cast<long long>(bChar);
    long long x = static_cast<long long>(xChar);

    // Намираме дължината на интервала (броя на елементите в него)
    long long intervalLength = (b - a) + 1;

    // Намираме текущата позиция на x спрямо началото на интервала (от 0 до intervalLength - 1)
    long long currentPosition = x - a;

    // Прилагаме цикличното изместване с операция остатък (модул).
    // Използваме (currentPosition + k) % intervalLength, за да работи правилно и при отрицателни k.
    long long newPosition = (currentPosition + k) % intervalLength;

    // Ако k е отрицателно, остатъкът в C++ може да бъде отрицателен,затова го коригираме, за да остане в границите на интервала: [0,intervalLength - 1]
    if (newPosition < 0) {
        newPosition += intervalLength;
    }

    // Връщаме се към абсолютния ASCII код, като добавим началото на интервала (a)
    long long finalCode = a + newPosition;

    // цяло число – ASCII кодът на символа, получен след изместването.
    cout << static_cast<char>(finalCode) << endl;

    return 0;
}