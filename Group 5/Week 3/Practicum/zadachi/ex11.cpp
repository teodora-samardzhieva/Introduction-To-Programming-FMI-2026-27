#include <iostream>
#include <algorithm>
using namespace std;

int main() {
    // Входни данни: 
    // a1, a2 за множество A; 
    // b1, b2 за множество B; 
    // 5-тото число (num)
    int a1, a2, b1, b2, num;
    cin >> a1 >> a2 >> b1 >> b2 >> num;

    // Определяне на границите на множествата (в случай на разменени входни числа)
    int minA = min(a1, a2);
    int maxA = max(a1, a2);
    int minB = min(b1, b2);
    int maxB = max(b1, b2);

    // Проверка дали числото принадлежи на съответните множества поотделно
    bool inA = (num >= minA && num <= maxA);
    bool inB = (num >= minB && num <= maxB);

    // 1. Обединение на A и B (A U B)
    bool inUnion = inA || inB;

    // 2. Сечение на A и B (A ∩ B)
    bool inIntersection = inA && inB;

    // 3. Разлика на A с B (A \ B)
    bool inDifference = inA && !inB;

    // 4. Принадлежи ли само в едно от множествата:
    // Елементът е само в едното множество, ако е в обединението, но НЕ е в сечението.
    bool inOnlyOne = inUnion && !inIntersection;

    // boolalpha - показва true/false вместо 1/0
    cout << boolalpha 
            << inUnion << ", " 
            << inIntersection << ", " 
            << inDifference << ", " 
            << inOnlyOne << endl;

    return 0;
}

