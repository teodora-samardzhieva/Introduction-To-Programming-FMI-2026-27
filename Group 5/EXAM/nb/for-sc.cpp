#include <iostream>

using namespace std;

int main() {
    for (int i = 0; i < 5; i++); { //! ;
        cout << i << " "; //! error: 'i' was not declared in this scope
    }

    return 0;
}

//! Грешка при компилация (Няма да се компилира).

// Точката и запетаята означава празно тяло на цикъла. Това празно тяло се повтаря, докато i < 5 (т.е. i нараства от 0 до 5 напълно „скрито“ в цикъла).

// Когато цикълът завърши, стойността на i става 5.
// Тъй като променливата i е дефинирана директно в заглавната част на for цикъла (int i = 0), нейният живот и видимост се ограничават само в рамките на самия цикъл.

// Цикълът си върти празно тяло от 0 до 5, но веднага след като приключи, променливата i се унищожава (излиза от обхват).

// Следващият блок { cout << i << " "; } се опитва да използва променлива i, която вече не съществува извън цикъла. В резултат компилаторът ще върне грешка: 'i' was not declared in this scope.