#include <iostream>

using namespace std;

int main() {
    int x = 1;
    int y = (x++, x * 10); // , отляво надясно и се взима резултата най-вдясно
    int z;
    z = 3, 4; // (z = 3), 4; // 4 се пренабрегва

    cout << x << ' ' << y << ' ' << z; // 2 20 3
}

// Операторът за запетая в C++ служи за последователно оценяване на изрази. 
// Той оценява лявата част, отхвърля резултата ѝ, след това оценява дясната част и връща нейната стойност като краен резултат.

// Редът с променливата y:
    // int y = (x++, x * 10);
    // Първо се изпълнява x++: стойността на x е 1, тя се увеличава на 2 (благодарение на инкремента).
    // След това се изчислява дясната част: x * 10 -> тъй като x вече е 2, резултатът е 2 x 10 = 20;
    // Тази стойност (20) се записва в променливата y.

// Към този момент: x = 2, а y = 20.

// Редът с променливата z:
    // z = 3, 4;
    // Тук трябва да внимаваме с приоритета на операторите: операторът за присвояване (=) е с по-висок приоритет от оператора за запетая (,).
    // Това означава, че изразът се изпълнява като: (z = 3), 4;.
    // Първо z приема стойност 3, а след това запетаята разделя отделен израз 4, който просто се пренебрегва.

// Към този момент: z = 3.

// Краен изход:
// cout << x << ' ' << y << ' ' << z; извежда съответно стойностите 2, 20 и 3.