#include <iostream>

using namespace std;

int main() {
    for (int i = 0; i < 2; i++) {
        for (i = 0; i < 3; i++) { // 0, 1, 2 -> 3 пъти
            cout << "C++" << " ";
        }
    }
}

// Краен резултат: "C++" се извежда точно 3 пъти.

// Тук във вътрешния цикъл пише for (i = 0; ...) без ключовата дума int.

// Това означава, че вътрешният цикъл не създава нова локална променлива, а използва и променя същата променлива i, която управлява външния цикъл.