#include <iostream>

using namespace std;

int main() {
    int x = 4;
    int i = 1;

    do {
        int y = 6;
        cout << i << " ";
        i++;
    } while (x < y);
}

// Обхват на променливите (Variable Scope):

// Променливата y е декларирана вътре в тялото на do-while цикъла (int y = 6;).

// В C++ обхватът на променливите, дефинирани в тялото на do блока, приключва с затварящата къдрава скоба } на самия блок, което се случва преди да се оцени условието в while (x < y).

// Грешка при компилация:

// Тъй като условието while (x < y) се опитва да използва променливата y, която вече е излязла от обхват и не съществува в този момент, компилаторът ще върне грешка ('y' was not declared in this scope).