#include <iostream>

using namespace std;

int main() {
    int x = 1; 
    int n = 2;
    // const int x = 1; //! ПАК ГРЕШКА
    // const int n = 2; // ВАЛИДНО

    switch (x) {
        case n: cout << 2;
            break;
        case x < 0: cout << "-";
            break;
        default: cout << "+";
    }
}

// Изисквания към case етикетите в C++:

// Според синтаксиса на езика C++, стойностите след думите case задължително трябва да бъдат константни изрази (стойности, които са известни по време на компилация, например конкретни числа като case 1: или константи const int n = 2;).

// Къде е проблемът в кода?

// case n: — Променливата n е обикновена, променлива локална променлива (int n = 2;), а не константа. Компилаторът не може да я третира като константен израз.

// case x < 0: — Изразът съдържа променливата x, чиято стойност се определя по време на изпълнение (runtime), така че това също не е компилационна константа.

// Поради тези причини кодът не може да бъде компилиран.

// Правилният отговор е d) Няма да се компилира!

//! case x < 0: продължава да НЕ се компилира: Макар че x е константа, изразът x < 0 връща булева стойност (false, т.е. 0). Въпреки че е константен израз, компилаторите в C++ изискват след case да стоят конкретни целочислени константи (или изрази, които се оценяват до цели числа/символи, а не булеви резултати от сравнения по този начин в някои контексти, или по-точно — x < 0 е валиден като число 0, но логическият израз като цяло пак може да се третира като нежелана практика или грешка спрямо типа).По-важното за изпитите е: case изисква цяло число или символ (като case 5:, акумулиран резултат или константа), а не булеви сравнения или булеви условия от типа x < 0.