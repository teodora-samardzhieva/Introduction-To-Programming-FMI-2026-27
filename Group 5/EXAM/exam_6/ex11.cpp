#include <iostream>

using namespace std;

int main() {

    int num1 = 5, num2 = 4;
    if (num1 > 0) {
        int num1 = 10, num2 = 20;
        cout << num1 + num2;
    }
    cout << num1 + num2;

    return 0;
}

