#include <iostream>

using namespace std;

// Задача. Ще се компилира ли програмният фрагмент? Обяснете защо мислите така. В случай, че компилацията е възможна, какво ще бъде изведено на стандартния изход след изпълнението му?

int a = -4;

int foo(int num) {
    return ++num - a;
}

int main() {
    int num = 51; int a = 3;

    a = ++num + 12;
    foo(a); cout << a;
}

// Да, програмният фрагмент ще се компилява успешно.
// Обосновка: Всички променливи са декларирани правилно с техните типове (int).
// Функцията foo приема параметър num и връща цяло число (int), като използва глобалната променлива a (декларирана най-горе със стойност -4). 
// Въпреки че в main() има локална променлива a, функциите извън main виждат глобалния обхват. В main() локалната променлива a се презаписва коректно("скрива" глобалната), извиква се foo(a) (чиито резултат просто не се записва никъде, но синтактично е напълно валидно) и се извежда a на стандартния изход с cout. 
// Изходът от програмата ще бъде: 64



/* 
   Обосновка за изхода на програмата (64):
   1. В main() локалните променливи са num = 51 и a = 3.
   2. Изразът a = ++num + 12:
      - ++num увеличава num на 52 (префиксен инкремент).
      - 52 + 12 прави 64.
      - Стойността 64 се записва в локалната променлива a.
   3. Функцията foo(a) се извиква с аргумент 64, но нейният 
      резултат не се присвоява и не се отпечатва.
   4. cout << a; извежда стойността на локалната променлива a, 
      която е 64.
*/