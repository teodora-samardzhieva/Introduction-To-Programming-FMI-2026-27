// При i = -4: условието връща -4 (true), i става -3, отпечатва се -3, а стъпката го прави -2.

// При i = -2: условието връща -2 (true), i става -1, отпечатва се -1, а стъпката го прави 0.

// Край на цикъла:

// Когато i стане 0, се прави следващата проверка за условие: i++ връща стойността 0. В езика C++ числото 0 се интерпретира като false.

