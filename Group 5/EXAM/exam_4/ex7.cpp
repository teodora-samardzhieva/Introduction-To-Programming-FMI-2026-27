// Проверка на условието (i++): Тъй като това е постфиксен инкремент в позицията за условие, изразът i++ връща старата стойност на i (което е -10), а след това увеличава i с 1 (става -9). Тъй като -10 е различно от 0 (възприема се като true), цикълът влиза в тялото си.

// Тяло на цикъла: Вътре в тялото i вече има стойност -9. Извежда се -9 (следвано от интервал и нов ред).

// Стъпка на цикъла (i++): В края на итерацията се изпълнява третата част на for цикъла, която увеличава i от -9 на -8.

// Следващи итерации:

// Процесът се повтаря за всяка четна отрицателна стойност:

// При i = -8: условието връща -8 (true), i става -7, отпечатва се -7, а стъпката го прави -6.

