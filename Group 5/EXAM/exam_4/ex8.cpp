// Задача. Ще се компилира ли програмният фрагмент? Обяснете защо мислите така. В случай, че компилацията е възможна, какво ще бъде изведено на стандартния изход след изпълнението му?

#include <iostream>

using namespace std;

int main() {
    int a = -1;
    int b = 2;
    a = b++ - 4;
    cout << a * ++b << endl;
}


// Да, програмният фрагмент ще се компилира успешно.

// Изход на програмата:
// -8

// Обосновка стъпка по стъпка:
// Инициализация:

// Променливата a започва със стойност -1.

// Променливата b започва със стойност 2.

// Изпълнение на реда a = b++ - 4;:

// Използва се постфиксен инкремент (b++), което означава, че в израза се взема текущата стойност на b (което е 2), а след това b се увеличава с 1 (става 3).

// Изчислява се изразът: 2 - 4 = -2.

// Новата стойност на a става -2.

// Към този момент променливите са: a = -2, а b = 3.

// Изпълнение на израза в cout (a * ++b):

// Взема се актуалната стойност на a, която е -2.

// Използва се префиксен инкремент (++b), който първо увеличава стойността на b с 1 (от 3 става 4) и след това връща новата стойност (4).

// Изчислява се произведението: -2 * 4 = -8.

// На стандартния изход се отпечатва -8.