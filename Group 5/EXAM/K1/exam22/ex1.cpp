#include <iostream>

using namespace std;

int main() {
    for (int i = 9; i >= 0; ----i)
        cout << i++ << endl;
    ;
    return 0;
}

// i---- = (i--)-- (rvalue)-- // ГРЕШКА! lvalue required as decrement operand

// --(--i)

// Инициализация: int i = 9; — цикълът започва с променлива i, равна на 9.
// Условие за край: i >= 0 — цикълът ще продължи да се изпълнява, докато i е по-голямо или равно на 0.
// Стъпка на цикъла: ----i — това всъщност са два последователни префиксни декремента (написани като (--(--i))). При всяка итерация стойността на i се намалява с 2 преди следващата проверка.
// Тяло на цикъла: cout << i++ << endl; — тук се използва постфиксен инкремент (i++). Това означава, че на екрана се отпечатва текущата стойност на i, а след това i се увеличава с 1.

// Итерация 1:
    // Начално състояние: i = 9.
    // Условие: 9 >= 0 е вярно (true).
    // Изпълнение на тялото: cout << i++; отпечатва текущата стойност 9, а след това i се увеличава с 1 и става 10.
    // Край на итерацията (Стъпка на цикъла): изпълнява се ----i. От текущата стойност 10 се изваждат 2 (--(--10)) и i става 8.

// Итерация 2:
    // Условие: 8 >= 0 е вярно (true).
    // Изпълнение на тялото: cout << i++; отпечатва 8, а след това i става 9.
    // Край на итерацията: от 9 се изваждат 2 чрез ----i и i става 7.

// Итерация 3:
    // Условие: 7 >= 0 е вярно (true).
    // Изпълнение на тялото: cout << i++; отпечатва 7, а след това i става 8.
    // Край на итерацията: от 8 се изваждат 2 и i става 6.

// Итерации 4 до 6 (продължава същата логика):
    // При итерация 4 се отпечатва 5 (крайно i става 4).
    // При итерация 5 се отпечатва 3 (крайно i става 2).
    // При итерация 6 се отпечатва 1 (крайно i става 0).

// Итерация 7:
    // Начално състояние за итерацията: i = 0.
    // Условие: 0 >= 0 е вярно (true).
    // Изпълнение на тялото: cout << i++; отпечатва 0, а след това i става 1.
    // Край на итерацията: от 1 се изваждат 2 (----i) и i става -1.

// Итерация 8 (Край на цикъла):
    // Условие: (i >= 0) -1 >= 0 е невярно (false). Цикълът прекъсва.

// Изход на екрана:
